  runtime_git_sha text not null check (runtime_git_sha ~ '^[0-9a-f]{40}$'),
  canonical_origin text not null,
  supabase_project_ref text not null,
  migration_head text not null check (migration_head ~ '^[0-9]{14}$'),
  schema_fingerprint text not null check (schema_fingerprint ~ '^[0-9a-f]{64}$'),
  cron_fingerprint text not null check (cron_fingerprint ~ '^[0-9a-f]{64}$'),
  manifest_fingerprint text not null check (manifest_fingerprint ~ '^[0-9a-f]{64}$'),
  clone_contract text not null,
  clone_rehearsal_blob_sha text not null check (clone_rehearsal_blob_sha ~ '^[0-9a-f]{40}$'),
  clone_ci_attestation text not null,
  frozen_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb
