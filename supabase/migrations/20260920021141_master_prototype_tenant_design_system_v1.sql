-- ROHMAT MASTER PROTOTIPE v1
-- Phase 7: tenant-scoped design-system state and version history.
-- Global registries/theme profiles remain platform-wide; tenant design state is isolated.

create table if not exists private.tenant_design_system_versions (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references private.platform_tenants(id) on delete cascade,
  kind text not null check(kind in ('baseline','draft','published','rollback')),
  theme_id text not null default 'custom',
  theme_name text not null default 'Custom Theme',
  payload jsonb not null,
  created_by text,
  restored_from bigint,
  created_at timestamptz not null default now()
);
create index if not exists tenant_design_system_versions_tenant_created_idx
  on private.tenant_design_system_versions(tenant_id,created_at desc,id desc);
alter table private.tenant_design_system_versions enable row level security;
revoke all on private.tenant_design_system_versions from anon,authenticated;
drop policy if exists tenant_design_system_versions_service_role_all on private.tenant_design_system_versions;
create policy tenant_design_system_versions_service_role_all
on private.tenant_design_system_versions for all to service_role using(true) with check(true);

