create or replace function public.admin_design_system_set_element_tenant(
  p_tenant_id uuid,p_token text,p_site text,p_page text,p_element text,p_config jsonb,p_publish boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_email extensions.citext;
  v_base jsonb;
  v_clean jsonb;
  v_path text[];
  v_existing jsonb;
  v_merged jsonb;
begin
  v_email:=private.tenant_admin_email_from_token(p_tenant_id,p_token);
  if v_email is null then return jsonb_build_object('ok',false,'error','invalid_session'); end if;
  if not exists(select 1 from public.design_element_registry r
    where r.site=p_site and r.page=p_page and r.element_id=p_element) then
    return jsonb_build_object('ok',false,'error','element_not_allowed');
  end if;
  v_clean:=private.design_sanitize_element_config(p_config);
  if v_clean='{}'::jsonb then return jsonb_build_object('ok',false,'error','empty_or_invalid_config'); end if;

  v_base:=private.tenant_design_base(p_tenant_id,p_publish);
  v_base:=jsonb_set(v_base,'{elements}',coalesce(v_base->'elements','{}'::jsonb),true);
  v_base:=jsonb_set(v_base,array['elements',p_site],coalesce(v_base#>array['elements',p_site],'{}'::jsonb),true);
  v_base:=jsonb_set(v_base,array['elements',p_site,p_page],coalesce(v_base#>array['elements',p_site,p_page],'{}'::jsonb),true);
  v_path:=array['elements',p_site,p_page,p_element];
  v_existing:=coalesce(v_base#>v_path,'{}'::jsonb);
  v_merged:=v_existing;
  if v_clean?'content' then v_merged:=jsonb_set(v_merged,'{content}',coalesce(v_merged->'content','{}'::jsonb)||(v_clean->'content'),true); end if;
  if v_clean?'typography' then v_merged:=jsonb_set(v_merged,'{typography}',coalesce(v_merged->'typography','{}'::jsonb)||(v_clean->'typography'),true); end if;
  if v_clean?'colors' then v_merged:=jsonb_set(v_merged,'{colors}',coalesce(v_merged->'colors','{}'::jsonb)||(v_clean->'colors'),true); end if;
  if v_clean?'layout' then v_merged:=jsonb_set(v_merged,'{layout}',coalesce(v_merged->'layout','{}'::jsonb)||(v_clean->'layout'),true); end if;
  v_base:=jsonb_set(v_base,v_path,v_merged,true);

  if coalesce(p_publish,false) then
    return private.tenant_design_system_apply_payload(p_tenant_id,v_email::text,v_base,'published',null);
  end if;
  return public.admin_design_system_save_draft_tenant(p_tenant_id,p_token,v_base);
end
$$;
