create table if not exists private.master_clone_rehearsal_attestations (
  id bigint generated by default as identity primary key,
  contract text not null,
  source_commit_sha text not null check (source_commit_sha ~ '^[0-9a-f]{40}$'),
  rehearsal_blob_sha text not null check (rehearsal_blob_sha ~ '^[0-9a-f]{40}$'),
  result jsonb not null,
  verified_at timestamptz not null default now(),
  unique(source_commit_sha,contract)
